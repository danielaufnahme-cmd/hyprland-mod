"""Turn a ``Bar`` into Waybar's config.jsonc, style.css and power menu file.

The app only ever writes inside its own folder (``~/.config/waybar/hyprland-mod``
by default, ``$HYPRLAND_MOD_WAYBAR_DIR`` in tests and dev); the user's own
``~/.config/waybar/config*`` is never touched.
"""

from __future__ import annotations

import json
import os
from pathlib import Path
from xml.sax.saxutils import escape

from ..core.fsutil import atomic_write
from .model import ZONES, Bar, validate_bar
from .modules import MODULES, POWER_ACTIONS, module_config, power_actions

HEADER = "Generated by Hyprland Mod. Edits here are replaced when you press “Use This Bar”."
CONFIG_NAME = "config.jsonc"
STYLE_NAME = "style.css"
MENU_NAME = "power-menu.xml"
FONT_FALLBACKS = ('"Symbols Nerd Font"', '"JetBrainsMono Nerd Font"', "sans-serif")
WEIGHT_CSS = {"normal": 400, "medium": 500, "bold": 700}
WARNING = "#f5c211"
CRITICAL = "#ff5f57"


def waybar_dir() -> Path:
    env = os.environ.get("HYPRLAND_MOD_WAYBAR_DIR")
    if env:
        return Path(env)
    base = os.environ.get("XDG_CONFIG_HOME") or os.path.expanduser("~/.config")
    return Path(base) / "waybar" / "hyprland-mod"


def paths(folder=None) -> dict[str, Path]:
    folder = Path(folder or waybar_dir())
    return {"config": folder / CONFIG_NAME, "style": folder / STYLE_NAME, "menu": folder / MENU_NAME}


# ---------------------------------------------------------------- config.jsonc

def config_dict(bar: Bar, folder=None) -> dict:
    bar = validate_bar(bar.to_dict())  # never trust an edited object blindly
    p = paths(folder)
    m = bar.margin if bar.floating else 0
    cfg = {
        "layer": "top",
        "position": bar.position,
        "height": bar.height,
        "spacing": bar.spacing,
        "exclusive": True,
        "reload_style_on_change": True,
        "margin-top": m if bar.position == "top" else 0,
        "margin-bottom": m if bar.position == "bottom" else 0,
        "margin-left": m,
        "margin-right": m,
    }
    for zone in ZONES:
        cfg[f"modules-{zone}"] = [MODULES[e["type"]]["waybar"] for e in bar.modules[zone]]
    for zone in ZONES:
        for e in bar.modules[zone]:
            cfg[MODULES[e["type"]]["waybar"]] = module_config(e["type"], e["options"], bar.icons, str(p["menu"]))
    return cfg


def generate_config(bar: Bar, folder=None) -> str:
    body = json.dumps(config_dict(bar, folder), indent=4, ensure_ascii=False)
    start = " ".join(command_preview(folder).split())  # no newlines can escape the comment
    return f"// {HEADER}\n// Start it with: {start}\n{body}\n"


def command_preview(folder=None) -> str:
    p = paths(folder)
    return f"waybar -c {p['config']} -s {p['style']}"


def strip_jsonc(text: str) -> str:
    """Remove // and /* */ comments outside of strings (enough for Waybar's JSONC)."""
    out, i, n, in_str = [], 0, len(text), False
    while i < n:
        c = text[i]
        if in_str:
            out.append(c)
            if c == "\\" and i + 1 < n:
                out.append(text[i + 1])
                i += 2
                continue
            if c == '"':
                in_str = False
            i += 1
        elif c == '"':
            in_str = True
            out.append(c)
            i += 1
        elif text.startswith("//", i):
            j = text.find("\n", i)
            i = n if j < 0 else j
        elif text.startswith("/*", i):
            j = text.find("*/", i + 2)
            i = n if j < 0 else j + 2
        else:
            out.append(c)
            i += 1
    return "".join(out)


# ---------------------------------------------------------------- style.css

def _rgb(hex_color: str) -> tuple[int, int, int]:
    h = hex_color.lstrip("#")
    return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)


def rgba(hex_color: str, alpha: float) -> str:
    r, g, b = _rgb(hex_color)
    return f"rgba({r}, {g}, {b}, {max(0.0, min(1.0, alpha)):.2f})"


def _block(selectors, rules: dict) -> str:
    sel = ",\n".join(selectors) if isinstance(selectors, (list, tuple)) else selectors
    body = "\n".join(f"  {k}: {v};" for k, v in rules.items())
    return f"{sel} {{\n{body}\n}}\n"


def generate_style(bar: Bar) -> str:
    bar = validate_bar(bar.to_dict())
    bg, fg, ac = bar.background, bar.foreground, bar.accent
    present = [e["type"] for z in ZONES for e in bar.modules[z]]
    ids = [f"#{MODULES[t]['css']}" for t in present]
    plain = [i for t, i in zip(present, ids) if t != "workspaces"]
    border = f"{bar.border}px solid {rgba(ac, 0.85)}" if bar.border else "none"
    radius_small = max(4, min(bar.radius, bar.height // 2) - 4)
    out = [f"/* {HEADER} */\n"]

    out.append(_block("*", {
        "font-family": ", ".join([f'"{bar.font}"', *FONT_FALLBACKS]),
        "font-size": f"{bar.font_size}px",
        "font-weight": WEIGHT_CSS[bar.font_weight],
        "min-height": 0,
        "border": "none",
        "border-radius": 0,
        "box-shadow": "none",
        "text-shadow": "none",
    }))

    win = {"color": fg}
    if bar.style == "solid":
        win["background-color"] = rgba(bg, bar.opacity)
        win["border-radius"] = f"{bar.radius if bar.floating else 0}px"
        win["border"] = border if bar.floating else "none"
        if bar.border and not bar.floating:
            edge = "bottom" if bar.position == "top" else "top"
            win[f"border-{edge}"] = border
    else:
        win["background-color"] = "transparent"
    out.append(_block("window#waybar", win))

    if bar.style == "solid":
        out.append(_block(".modules-left", {"padding-left": f"{bar.padding}px"}))
        out.append(_block(".modules-right", {"padding-right": f"{bar.padding}px"}))
    elif bar.style == "islands":
        zones = [f".modules-{z}" for z in ZONES if bar.modules[z]]
        if zones:
            out.append(_block(zones, {
                "background-color": rgba(bg, bar.opacity),
                "border-radius": f"{bar.radius}px",
                "border": border,
                "padding": f"0 {bar.padding}px",
            }))
        if not bar.floating:
            out.append(_block(".modules-left", {"margin-left": "6px"}))
            out.append(_block(".modules-right", {"margin-right": "6px"}))
            out.append(_block(["window#waybar > box"], {"padding": "4px 0"}))
    else:  # pills: every module is its own capsule
        if ids:
            out.append(_block(ids, {
                "background-color": rgba(bg, bar.opacity),
                "border-radius": f"{bar.radius}px",
                "border": border,
                "margin": "4px 0",
            }))
        out.append(_block(".modules-left", {"margin-left": "6px"}))
        out.append(_block(".modules-right", {"margin-right": "6px"}))

    out.append(_block("#workspaces", {"padding": "0 4px"}))
    out.append(_block("#workspaces button", {
        "padding": "0 8px",
        "margin": "4px 1px",
        "color": rgba(fg, 0.55),
        "background-color": "transparent",
        "border-radius": f"{radius_small}px",
        "transition": "all 150ms ease-out",
    }))
    out.append(_block("#workspaces button.empty", {"color": rgba(fg, 0.32)}))
    out.append(_block("#workspaces button:hover", {"color": fg, "background-color": rgba(fg, 0.10)}))
    out.append(_block("#workspaces button.active", {"color": ac, "background-color": rgba(ac, 0.18)}))
    out.append(_block("#workspaces button.urgent", {"color": "#ffffff", "background-color": CRITICAL}))
    if plain:
        out.append(_block(plain, {"padding": f"0 {bar.padding}px", "color": fg}))
    out.append(_block(["#battery.warning:not(.charging)"], {"color": WARNING}))
    out.append(_block(["#battery.critical:not(.charging)", "#temperature.critical"], {"color": CRITICAL}))
    out.append(_block(["#network.disconnected", "#pulseaudio.muted", "#wireplumber.muted",
                       "#bluetooth.off", "#bluetooth.disabled"], {"color": rgba(fg, 0.45)}))
    out.append(_block(["#idle_inhibitor.activated", "#custom-power", "#battery.charging"], {"color": ac}))
    out.append(_block("#keyboard-state label", {"padding": "0 4px", "color": rgba(fg, 0.45)}))
    out.append(_block("#keyboard-state label.locked", {"color": ac}))
    out.append(_block("#window", {"color": rgba(fg, 0.85)}))
    out.append(_block("window#waybar.empty #window", {"background-color": "transparent", "border": "none"}))
    out.append(_block("tooltip", {
        "background-color": rgba(bg, 0.97),
        "border": f"1px solid {rgba(fg, 0.12)}",
        "border-radius": "10px",
    }))
    out.append(_block("tooltip label", {"color": fg, "padding": "2px 4px"}))
    out.append(_block("menu", {
        "background-color": rgba(bg, 0.98),
        "color": fg,
        "border": f"1px solid {rgba(fg, 0.12)}",
        "border-radius": "10px",
        "padding": "6px",
    }))
    out.append(_block("menuitem", {"padding": "6px 12px", "border-radius": "6px"}))
    out.append(_block("menuitem:hover", {"background-color": rgba(ac, 0.22), "color": fg}))
    out.append(_block("#tray > .needs-attention", {"background-color": rgba(CRITICAL, 0.4)}))
    return "\n".join(out)


# ---------------------------------------------------------------- power menu

def generate_menu(bar: Bar) -> str:
    opts = bar.options("power") if bar.find("power") else {}
    items = power_actions(opts) if opts else POWER_ACTIONS
    lines = ['<?xml version="1.0" encoding="UTF-8"?>', "<!-- " + escape(HEADER) + " -->", "<interface>",
             '  <object class="GtkMenu" id="menu">']
    for i, (aid, label, _cmd) in enumerate(items):
        if aid == "reboot" and i:
            lines.append('    <child><object class="GtkSeparatorMenuItem" id="sep"/></child>')
        lines.append(f'    <child><object class="GtkMenuItem" id="{escape(aid)}">'
                     f'<property name="label">{escape(label)}</property></object></child>')
    lines += ["  </object>", "</interface>", ""]
    return "\n".join(lines)


# ---------------------------------------------------------------- files

def render(bar: Bar, folder=None) -> dict[str, str]:
    return {"config": generate_config(bar, folder), "style": generate_style(bar), "menu": generate_menu(bar)}


def write_files(bar: Bar, folder=None) -> dict[str, Path]:
    """Write config.jsonc, style.css and power-menu.xml into the app's own folder."""
    p = paths(folder)
    texts = render(bar, folder)
    for key in ("menu", "style", "config"):
        atomic_write(str(p[key]), texts[key])
    return p


def files_match(bar: Bar, folder=None) -> bool:
    """True when the files on disk are exactly what this design generates."""
    p = paths(folder)
    try:
        texts = render(bar, folder)
        return all(p[k].read_text(encoding="utf-8") == texts[k] for k in texts)
    except (OSError, UnicodeDecodeError, ValueError):
        return False
