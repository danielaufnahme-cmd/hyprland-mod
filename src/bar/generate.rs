//! Waybar configuration and style generator.

use anyhow::Result;
use serde_json::{json, Map, Value};
use std::fs;
use std::path::{Path, PathBuf};

use super::model::Bar;
use super::modules::{default_module_config, module_waybar_name};
use crate::core::fsutil::atomic_write;

pub fn waybar_dir() -> PathBuf {
    if let Ok(env) = std::env::var("HYPRLAND_MOD_WAYBAR_DIR") {
        return PathBuf::from(env);
    }
    let base = dirs::config_dir().unwrap_or_else(|| PathBuf::from(".config"));
    base.join("waybar").join("hyprland-mod")
}

pub fn generate_config(bar: &Bar) -> String {
    let mut map = Map::new();
    map.insert("layer".into(), json!("top"));
    map.insert("position".into(), json!(bar.position));
    map.insert("height".into(), json!(bar.height));
    map.insert("spacing".into(), json!(bar.spacing));
    map.insert("exclusive".into(), json!(true));
    map.insert("reload_style_on_change".into(), json!(true));

    let m = if bar.floating { bar.margin } else { 0 };
    map.insert(
        "margin-top".into(),
        json!(if bar.position == "top" { m } else { 0 }),
    );
    map.insert(
        "margin-bottom".into(),
        json!(if bar.position == "bottom" { m } else { 0 }),
    );
    map.insert("margin-left".into(), json!(m));
    map.insert("margin-right".into(), json!(m));

    let left_names: Vec<&str> = bar
        .modules
        .left
        .iter()
        .map(|m| module_waybar_name(&m.r#type))
        .collect();
    let center_names: Vec<&str> = bar
        .modules
        .center
        .iter()
        .map(|m| module_waybar_name(&m.r#type))
        .collect();
    let right_names: Vec<&str> = bar
        .modules
        .right
        .iter()
        .map(|m| module_waybar_name(&m.r#type))
        .collect();

    map.insert("modules-left".into(), json!(left_names));
    map.insert("modules-center".into(), json!(center_names));
    map.insert("modules-right".into(), json!(right_names));

    for m in bar
        .modules
        .left
        .iter()
        .chain(&bar.modules.center)
        .chain(&bar.modules.right)
    {
        let name = module_waybar_name(&m.r#type);
        let cfg = default_module_config(&m.r#type, &m.options, bar.icons);
        map.insert(name.into(), cfg);
    }

    let val = Value::Object(map);
    let body = serde_json::to_string_pretty(&val).unwrap_or_default();
    format!(
        "// Generated by Hyprland Mod. Edits here will be overwritten.\n{}\n",
        body
    )
}

pub fn generate_style(bar: &Bar) -> String {
    format!(
        r#"/* Generated by Hyprland Mod */
* {{
    font-family: "Symbols Nerd Font", "JetBrainsMono Nerd Font", sans-serif;
    font-size: 13px;
    min-height: 0;
}}

window#waybar {{
    background-color: {bg};
    color: {fg};
    border-radius: {radius}px;
    transition-property: background-color;
    transition-duration: .5s;
}}

#workspaces button {{
    padding: 0 5px;
    background-color: transparent;
    color: {fg};
}}

#workspaces button.active {{
    background-color: rgba(255, 255, 255, 0.15);
    border-radius: {btn_radius}px;
}}

#clock,
#battery,
#cpu,
#memory,
#pulseaudio,
#network,
#tray {{
    padding: 0 10px;
    margin: 4px 2px;
    background-color: rgba(255, 255, 255, 0.08);
    border-radius: {btn_radius}px;
}}
"#,
        bg = bar.bg_color,
        fg = bar.fg_color,
        radius = bar.radius,
        btn_radius = (bar.radius / 2).max(4)
    )
}

pub fn write_bar_files<P: AsRef<Path>>(bar: &Bar, dir: Option<P>) -> Result<PathBuf> {
    let out_dir = match dir {
        Some(d) => d.as_ref().to_path_buf(),
        None => waybar_dir(),
    };
    fs::create_dir_all(&out_dir)?;

    let config_path = out_dir.join("config.jsonc");
    let style_path = out_dir.join("style.css");

    atomic_write(&config_path, &generate_config(bar))?;
    atomic_write(&style_path, &generate_style(bar))?;

    Ok(out_dir)
}
