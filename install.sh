#!/usr/bin/env bash
# Hyprland Mod installer (user-local, no sudo, never touches your Hyprland config).
#   ./install.sh
#   curl -fsSL https://raw.githubusercontent.com/danielaufnahme-cmd/hyprland-mod/main/install.sh | bash
set -euo pipefail

# GitHub user hosting the repository
OWNER="danielaufnahme-cmd"
REPO_URL="https://github.com/${OWNER}/hyprland-mod"
BRANCH="main"

APP_ID="io.github.HyprlandMod"
DATA_HOME="${XDG_DATA_HOME:-$HOME/.local/share}"
APP_DIR="$DATA_HOME/hyprland-mod/app"
BIN_DIR="$HOME/.local/bin"
LAUNCHER="$BIN_DIR/hyprland-mod"
DESKTOP_DIR="$DATA_HOME/applications"
ICON_DIR="$DATA_HOME/icons/hicolor/scalable/apps"

if [ -t 1 ]; then
  B=$'\033[1m'; G=$'\033[32m'; Y=$'\033[33m'; R=$'\033[31m'; C=$'\033[36m'; N=$'\033[0m'
else
  B=""; G=""; Y=""; R=""; C=""; N=""
fi
step() { printf '%s==>%s %s%s%s\n' "$C" "$N" "$B" "$*" "$N"; }
ok()   { printf '  %s✓%s %s\n' "$G" "$N" "$*"; }
warn() { printf '  %s!%s %s\n' "$Y" "$N" "$*"; }
die()  { printf '%s✗ %s%s\n' "$R" "$*" "$N" >&2; exit 1; }

printf '\n%sHyprland Mod%s installer\n\n' "$B" "$N"

# --- locate source ----------------------------------------------------------
SRC=""
TMP=""
cleanup() { if [ -n "$TMP" ]; then rm -rf "$TMP"; fi; }
trap cleanup EXIT

script_dir=""
if [ -n "${BASH_SOURCE[0]:-}" ] && [ -f "${BASH_SOURCE[0]}" ]; then
  script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
fi
if [ -n "$script_dir" ] && [ -d "$script_dir/hyprland_mod" ]; then
  SRC="$script_dir"
else
  step "Downloading Hyprland Mod"
  command -v git >/dev/null 2>&1 || die "git is required to download Hyprland Mod."
  TMP="$(mktemp -d)"
  git clone --quiet --depth 1 --branch "$BRANCH" "$REPO_URL" "$TMP/src" || die "Could not clone $REPO_URL"
  SRC="$TMP/src"
  ok "Fetched $REPO_URL"
fi

# --- dependencies -----------------------------------------------------------
step "Checking dependencies"
dep_ok=1
if ! command -v python3 >/dev/null 2>&1; then
  dep_ok=0
  warn "python3 not found"
elif ! python3 - <<'PY' >/dev/null 2>&1
import sys
assert sys.version_info >= (3, 11)
import gi
gi.require_version("Gtk", "4.0")
gi.require_version("Adw", "1")
from gi.repository import Gtk, Adw
assert (Adw.MAJOR_VERSION, Adw.MINOR_VERSION) >= (1, 5)
PY
then
  dep_ok=0
  warn "Need Python 3.11+, PyGObject, GTK 4 and libadwaita 1.5+"
fi

if [ "$dep_ok" -eq 1 ]; then
  ok "Python, PyGObject, GTK 4 and libadwaita are ready"
else
  printf '\n  Install the missing packages for your distribution, then re-run this script:\n\n'
  printf '    Arch:            sudo pacman -S --needed python python-gobject gtk4 libadwaita\n'
  printf '    Fedora:          sudo dnf install python3 python3-gobject gtk4 libadwaita\n'
  printf '    Debian/Ubuntu:   sudo apt install python3 python3-gi gir1.2-gtk-4.0 gir1.2-adw-1\n'
  printf '    openSUSE:        sudo zypper install python3 python3-gobject typelib-1_0-Gtk-4_0 typelib-1_0-Adw-1\n\n'
  die "Missing dependencies (nothing was installed)."
fi

if [ -z "${HYPRLAND_INSTANCE_SIGNATURE:-}" ] && [ "${XDG_CURRENT_DESKTOP:-}" != "Hyprland" ]; then
  warn "Hyprland does not seem to be running; the app can still edit config, but live preview needs Hyprland."
fi

# --- install ----------------------------------------------------------------
step "Installing to $APP_DIR"
rm -rf "$APP_DIR"
mkdir -p "$APP_DIR"
for d in hyprland_mod data styles; do
  [ -d "$SRC/$d" ] && cp -r "$SRC/$d" "$APP_DIR/$d"
done
find "$APP_DIR" -name '__pycache__' -type d -prune -exec rm -rf {} +
ok "Application files"

mkdir -p "$BIN_DIR"
cat > "$LAUNCHER" <<LAUNCH
#!/usr/bin/env bash
# Generated by Hyprland Mod install.sh
export PYTHONPATH="$APP_DIR\${PYTHONPATH:+:\$PYTHONPATH}"
exec python3 -m hyprland_mod "\$@"
LAUNCH
chmod +x "$LAUNCHER"
ok "Launcher $LAUNCHER"

mkdir -p "$DESKTOP_DIR" "$ICON_DIR"
sed "s|^Exec=.*|Exec=$LAUNCHER|" "$SRC/data/$APP_ID.desktop" > "$DESKTOP_DIR/$APP_ID.desktop"
ok "Menu entry"
cp "$SRC/data/icons/$APP_ID.svg" "$ICON_DIR/$APP_ID.svg"
if [ -f "$SRC/data/icons/$APP_ID-symbolic.svg" ]; then
  cp "$SRC/data/icons/$APP_ID-symbolic.svg" "$ICON_DIR/$APP_ID-symbolic.svg"
fi
ok "Icon"

if command -v update-desktop-database >/dev/null 2>&1; then
  update-desktop-database "$DESKTOP_DIR" >/dev/null 2>&1 || true
fi
if command -v gtk-update-icon-cache >/dev/null 2>&1; then
  gtk-update-icon-cache -q -t -f "$DATA_HOME/icons/hicolor" >/dev/null 2>&1 || true
fi

printf '\n%s✓ Hyprland Mod is installed.%s\n' "$G$B" "$N"
printf '  Open %sHyprland Mod%s from your app launcher (or run %shyprland-mod%s).\n' "$B" "$N" "$B" "$N"
case ":$PATH:" in
  *":$BIN_DIR:"*) ;;
  *) warn "$BIN_DIR is not in your PATH; the app launcher entry still works." ;;
esac
printf '  Re-run this script any time to upgrade.\n\n'
